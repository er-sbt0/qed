/**
 * build-examples.mjs — inline the example programs as few-shot examples.
 *
 * WHICH programs is `examples/manifest.json`'s business, not this script's: it
 * loops over whatever the manifest lists, so adding or dropping an example
 * needs no edit here. See `examples/README.md` for what an example is for.
 *
 * The one edit made to a program: its `import ... from "./api"` lines are
 * dropped, because a generated program receives the scope as ambient globals
 * and must not import. Those lines are the entire difference between an example
 * and the artifact we ask the model for, which is why it is worth generating
 * this file instead of hand-copying the programs (they would drift).
 *
 * A program with no import line is not an error: `./run.sh record` promotes
 * REAL model output into examples/, and model output already has no imports —
 * it was written for the ambient scope in the first place. Only an import that
 * SURVIVES stripping is a defect, because that program would fail the gate.
 *
 * Type ANNOTATIONS stay: esbuild erases annotations without resolving them, so
 * a program may name library types in a closure parameter with nothing
 * imported.
 *
 * Regenerate with `./run.sh examples`, and commit the output — the web app must
 * not read the repo at runtime.
 */
import { transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');

/** discipline → the example that demonstrates it (see plan.ts DISCIPLINES). */
const { examples: EXAMPLES } = JSON.parse(
  await readFile(join(repo, 'examples', 'manifest.json'), 'utf8'),
);

/** both `import { M } from "./api"` and `import type { Word } from "./api"`. */
const IMPORT_LINE = /^[ \t]*import\s+(?:type\s+)?\{[^}]*\}\s+from\s+["']\.\/api["'];?[ \t]*\n/gm;

const entries = [];
for (const ex of EXAMPLES) {
  const path = join(repo, 'examples', ex.dir, 'beats.ts');
  const raw = await readFile(path, 'utf8');
  const source = raw.replace(IMPORT_LINE, '').replace(/\n{3,}/g, '\n\n').trim();
  if (/^[ \t]*import\s/m.test(source)) {
    throw new Error(`${path}: an import survived stripping — the example would fail the gate`);
  }
  // Type-stripped here too, so the example gallery is static: no compile
  // endpoint, no API key, nothing to fetch. These options MUST match
  // compileProgram's — compile.test.ts asserts they still do.
  const { code: js } = await transform(source, {
    loader: 'ts',
    format: 'iife',
    target: 'es2020',
    keepNames: true,
  });
  entries.push({ ...ex, source, js });
}

const body = entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.key)}: {\n` +
      `    title: ${JSON.stringify(e.title)},\n` +
      `    dir: ${JSON.stringify(e.dir)},\n` +
      `    source: ${JSON.stringify(e.source)},\n` +
      `    js: ${JSON.stringify(e.js)},\n` +
      `  },`,
  )
  .join('\n');

const out = `/**
 * GENERATED by scripts/build-examples.mjs — do not edit.
 *
 * The programs listed in examples/manifest.json, with their \`./api\` import
 * stripped: executed lesson programs used as few-shot examples for the
 * generation prompt and as the web app's example gallery. Edit the programs
 * under examples/, then re-run \`./run.sh examples\`.
 */

export interface ExampleProgram {
  readonly title: string;
  /** the directory under examples/ it came from */
  readonly dir: string;
  /** the program source, ready to run (no imports) */
  readonly source: string;
  /** type-stripped, ready for QuickJS — the same transform the gate applies */
  readonly js: string;
}

export const EXAMPLE_PROGRAMS: Readonly<Record<string, ExampleProgram>> = {
${body}
};
`;

const dest = join(here, '..', 'src', 'examples.generated.ts');
await writeFile(dest, out);
console.log(`wrote ${dest} (${entries.length} programs, ${out.length} bytes)`);
