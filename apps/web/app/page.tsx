'use client';

/**
 * The workbench, on the program path.
 *
 * An answer is now a PROGRAM, not a validated scene, so the page's job changed:
 * it no longer re-validates a data structure before trusting it to render — it
 * hands the program to a sandbox and listens for what goes wrong. The two
 * failure modes are surfaced differently on purpose:
 *
 *  - the STATIC gate rejected it (no program came back) — the answer degrades
 *    to prose, and the reason is shown;
 *  - the program threw while RUNNING — one repair round-trip is offered, which
 *    is the loop that makes an open vocabulary survivable.
 *
 * The example is the markov acceptance program, running through exactly the
 * same component as a generated answer.
 */

import { useMemo, useRef, useState } from 'react';
import { Button } from '@/components/ui/button';
import { LessonCanvas } from '@/components/lesson-canvas';
import { MathText } from '@/components/math';
import { ThemeToggle } from '@/components/theme-toggle';
// Client-safe subpaths only: the planner barrel reaches esbuild and the SDK,
// which must never be pulled into the browser bundle.
import { EXAMPLE_PROGRAMS } from '@math-ai/planner/examples';
import type { AnswerPlan } from '@math-ai/planner/plan';

/**
 * The gallery is whatever the corpus currently holds — derived, never listed.
 *
 * It used to name its tabs here (`{key: 'probability', tab: 'Markov chain'}`),
 * which quietly made one lesson load-bearing: `examples/` is regenerated by
 * `./run.sh record` a discipline at a time, so a hardcoded key becomes an
 * undefined lookup and a blank page the moment that discipline is re-recorded
 * under a new slug. Reading `EXAMPLE_PROGRAMS` means the page follows the
 * corpus by construction and cannot rot against it.
 *
 * The tab label is the discipline, not the lesson title: titles are model-
 * written and run long, and the discipline is the axis the corpus is keyed on.
 */
const EXAMPLE_ORDER = Object.keys(EXAMPLE_PROGRAMS).map((key) => ({
  key,
  tab: key.replace(/-/g, ' '),
}));

const EXAMPLE_QUESTIONS = [
  'Explain the Fundamental Theorem of Calculus',
  'What does the determinant of a 2×2 matrix mean?',
  'Why does a Markov chain converge to a stationary distribution?',
  'Explain the pigeonhole principle',
];

interface ProgramPayload {
  source: string;
  js: string;
  findings: Array<{ severity: string; rule: string; message: string }>;
}

interface Answer {
  plan: AnswerPlan;
  explanation: string;
  program: ProgramPayload | null;
  failure: { stage: string; errors: string[] } | null;
  attempts: number;
}

interface HistoryItem {
  id: string;
  question: string;
  answer: Answer;
  /** set when the sandbox rejected the program at runtime */
  runtimeError?: string;
  repairing?: boolean;
  repairFailed?: string;
}

/** One read-only conversational turn about the scene on screen (roadmap 4a). */
interface FollowupTurn {
  question: string;
  answer?: string;
  error?: string;
}

export default function Page() {
  const [question, setQuestion] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [history, setHistory] = useState<HistoryItem[]>([]);
  const [activeId, setActiveId] = useState<string | null>(null);
  const [pendingQuestion, setPendingQuestion] = useState<string | null>(null);
  const [showSource, setShowSource] = useState(false);

  /**
   * A describer for the live scene, handed up by LessonCanvas and replaced on
   * every rebuild. A ref rather than state on purpose: it changes on every
   * backward jump, and re-rendering the page for that would remount the canvas
   * that just handed it to us.
   */
  const describeScene = useRef<(() => unknown) | null>(null);
  const [followups, setFollowups] = useState<FollowupTurn[]>([]);
  const [followup, setFollowup] = useState('');
  const [asking, setAsking] = useState(false);

  const active = useMemo(
    () => history.find((h) => h.id === activeId) ?? null,
    [history, activeId],
  );
  const onHome = activeId === null && pendingQuestion === null;

  function patch(id: string, change: Partial<HistoryItem>) {
    setHistory((prev) => prev.map((h) => (h.id === id ? { ...h, ...change } : h)));
  }

  async function ask(q: string) {
    const query = q.trim();
    if (!query || loading) return;
    setLoading(true);
    setError(null);
    setActiveId(null);
    setPendingQuestion(query);
    try {
      const res = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ question: query }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? `request failed (${res.status})`);
      const item: HistoryItem = { id: crypto.randomUUID(), question: query, answer: data as Answer };
      setHistory((prev) => [item, ...prev]);
      setActiveId(item.id);
      setQuestion('');
    } catch (e) {
      setError(e instanceof Error ? e.message : 'something went wrong');
    } finally {
      setLoading(false);
      setPendingQuestion(null);
    }
  }

  /** Hand a runtime diagnostic back to the model for one corrected program. */
  async function repair(item: HistoryItem) {
    if (!item.answer.program || !item.runtimeError) return;
    patch(item.id, { repairing: true, repairFailed: undefined });
    try {
      const res = await fetch('/api/repair', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
          question: item.question,
          plan: item.answer.plan,
          source: item.answer.program.source,
          errors: [item.runtimeError],
        }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? `repair failed (${res.status})`);
      if (!data.program) {
        throw new Error(
          `the repair did not pass the gate (${data.failure?.stage}): ${
            data.failure?.errors?.join('; ') ?? 'unknown'
          }`,
        );
      }
      patch(item.id, {
        answer: { ...item.answer, program: data.program },
        runtimeError: undefined,
        repairing: false,
      });
    } catch (e) {
      patch(item.id, {
        repairing: false,
        repairFailed: e instanceof Error ? e.message : 'repair failed',
      });
    }
  }

  /**
   * Ask about the scene as it stands. READ-ONLY: the answer is prose, nothing
   * in the scene moves. The manifest is read at the moment of asking, so it
   * carries whatever the student has dragged since the lesson was generated —
   * which is the entire reason this cannot be answered from the program text.
   */
  async function askAboutScene() {
    const q = followup.trim();
    const describe = describeScene.current;
    if (!q || asking || !describe || !active) return;
    setAsking(true);
    setFollowup('');
    const turn: FollowupTurn = { question: q };
    setFollowups((prev) => [...prev, turn]);
    try {
      const res = await fetch('/api/followup', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
          question: q,
          manifest: describe(),
          originalQuestion: active.question,
        }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? `request failed (${res.status})`);
      setFollowups((prev) => prev.map((t) => (t === turn ? { ...t, answer: data.answer } : t)));
    } catch (e) {
      const message = e instanceof Error ? e.message : 'could not answer that';
      setFollowups((prev) => prev.map((t) => (t === turn ? { ...t, error: message } : t)));
    } finally {
      setAsking(false);
    }
  }

  const [exampleKey, setExampleKey] = useState<string>(EXAMPLE_ORDER[0]?.key ?? '');
  const example = EXAMPLE_PROGRAMS[exampleKey];

  return (
    <div className="app">
      {/* ---- sidebar ---- */}
      <aside className="sidebar">
        <div className="brand">
          <span className="glyph">f(x)&rsaquo;</span>
          <div>
            <p className="eyebrow">Reactive canvas</p>
            <h1>Math AI</h1>
          </div>
        </div>

        <nav className="side-nav" aria-label="Primary">
          <button
            className="nav-item nav-home"
            aria-current={onHome ? 'page' : undefined}
            onClick={() => {
              setActiveId(null);
              setPendingQuestion(null);
              setError(null);
            }}
          >
            <span className="nav-ico" aria-hidden="true">
              ⌂
            </span>
            Home
          </button>
        </nav>

        <div className="recent">
          <p className="eyebrow">Recent</p>
          {history.length === 0 ? (
            <p className="recent-empty">Questions you ask appear here for this session.</p>
          ) : (
            <ul className="recent-list">
              {history.map((h) => (
                <li key={h.id}>
                  <button
                    className="nav-item recent-item"
                    aria-current={h.id === activeId ? 'page' : undefined}
                    title={h.question}
                    onClick={() => {
                      setActiveId(h.id);
                      setPendingQuestion(null);
                      setError(null);
                    }}
                  >
                    {h.question}
                  </button>
                </li>
              ))}
            </ul>
          )}
        </div>

        <div className="sidebar-foot">
          <ThemeToggle />
        </div>
      </aside>

      {/* ---- main ---- */}
      <main className="main">
        <div className="main-inner">
          <section className="ask">
            {onHome && (
              <p className="sub">
                Ask a math question. The model answers by writing a <b>lesson program</b> — a live
                explanation that unfolds and then lets you drag it. It runs sandboxed, in your
                browser.
              </p>
            )}
            <form
              onSubmit={(e) => {
                e.preventDefault();
                void ask(question);
              }}
            >
              <input
                type="text"
                placeholder="Ask about a theorem, a derivative, a matrix…"
                value={question}
                onChange={(e) => setQuestion(e.target.value)}
                aria-label="Math question"
              />
              <Button type="submit" disabled={loading || question.trim().length === 0}>
                {loading ? 'Thinking…' : 'Ask'}
              </Button>
            </form>
            {onHome && (
              <div className="chips">
                {EXAMPLE_QUESTIONS.map((q) => (
                  <button
                    key={q}
                    className="chip"
                    disabled={loading}
                    onClick={() => {
                      setQuestion(q);
                      void ask(q);
                    }}
                  >
                    {q}
                  </button>
                ))}
              </div>
            )}
          </section>

          {error && (
            <p className="error" role="alert">
              {error}
            </p>
          )}

          {pendingQuestion && (
            <section className="stage" aria-live="polite">
              <header className="stage-head">
                <p className="eyebrow">Planning, then writing the program…</p>
                <h2 className="stage-q">{pendingQuestion}</h2>
              </header>
              <div className="answer">
                <div className="thinking" aria-hidden="true">
                  <span />
                  <span />
                  <span />
                </div>
              </div>
            </section>
          )}

          {!pendingQuestion && active && (
            <section className="stage" aria-live="polite">
              <header className="stage-head">
                <p className="eyebrow">
                  Answer · {active.answer.plan.topic}
                  {active.answer.attempts > 1 && ' · repaired once'}
                </p>
                <h2 className="stage-q">{active.question}</h2>
              </header>
              <div className="answer">
                <p className="answer-blurb">
                  <MathText text={active.answer.explanation} />
                </p>

                {active.answer.program ? (
                  <>
                    <LessonCanvas
                      key={`${active.id}-${active.answer.program.source.length}`}
                      js={active.answer.program.js}
                      source={active.answer.program.source}
                      onRuntimeError={(message) => patch(active.id, { runtimeError: message })}
                      onSceneChange={(describe) => {
                        describeScene.current = describe;
                      }}
                    />
                    {active.runtimeError && (
                      <div className="repair">
                        <p>
                          The program failed in the sandbox. The diagnostic can go back to the
                          model for one corrected version.
                        </p>
                        <Button onClick={() => void repair(active)} disabled={active.repairing}>
                          {active.repairing ? 'Repairing…' : 'Repair it'}
                        </Button>
                        {active.repairFailed && <p className="error">{active.repairFailed}</p>}
                      </div>
                    )}
                    <div className="followups">
                      {followups.map((t, i) => (
                        <div key={i} className="followup-turn">
                          <p className="followup-q">{t.question}</p>
                          {t.answer && (
                            <p className="followup-a">
                              <MathText text={t.answer} />
                            </p>
                          )}
                          {t.error && <p className="error">{t.error}</p>}
                          {!t.answer && !t.error && (
                            <div className="thinking" aria-hidden="true">
                              <span />
                              <span />
                              <span />
                            </div>
                          )}
                        </div>
                      ))}
                      <form
                        className="followup-ask"
                        onSubmit={(e) => {
                          e.preventDefault();
                          void askAboutScene();
                        }}
                      >
                        <input
                          value={followup}
                          onChange={(e) => setFollowup(e.target.value)}
                          placeholder="Ask about what you see — drag something first, then ask why"
                          aria-label="Ask about the scene"
                          disabled={asking}
                        />
                        <Button type="submit" disabled={asking || followup.trim() === ''}>
                          {asking ? 'Looking…' : 'Ask'}
                        </Button>
                      </form>
                    </div>
                    <div className="answer-foot">
                      <button className="chip" onClick={() => setShowSource((s) => !s)}>
                        {showSource ? 'Hide' : 'Show'} the program
                      </button>
                    </div>
                    {showSource && <pre className="program">{active.answer.program.source}</pre>}
                  </>
                ) : (
                  <p className="warn">
                    {active.answer.failure
                      ? `No program: the ${active.answer.failure.stage} gate rejected it — ${active.answer.failure.errors.join('; ')}`
                      : 'The plan judged that prose answers this better than a picture.'}
                  </p>
                )}
              </div>
            </section>
          )}

          {onHome && (
            <>
              <section className="examples">
                <p className="eyebrow">Example programs</p>
                <p className="examples-sub">
                  Lessons recorded from the model, replayed through the same sandbox.
                </p>
                <nav className="tabs" role="tablist" aria-label="Example programs">
                  {EXAMPLE_ORDER.map((s) => (
                    <button
                      key={s.key}
                      role="tab"
                      aria-selected={s.key === exampleKey}
                      className="tab"
                      onClick={() => setExampleKey(s.key)}
                    >
                      {s.tab}
                    </button>
                  ))}
                </nav>
                {example && (
                  <div className="answer">
                    <h2 className="answer-title">{example.title}</h2>
                    <p className="example-src">
                      <code>examples/{example.dir}/beats.ts</code>, executed unmodified.
                    </p>
                    <LessonCanvas key={exampleKey} js={example.js} source={example.source} />
                  </div>
                )}
              </section>

              <footer className="note">
                <b>How it works:</b> the model writes a TypeScript <em>lesson program</em> against a
                semantic authoring API. A static lint gates it; QuickJS-wasm runs it in your
                browser; runtime diagnostics go back for repair. Ask requires{' '}
                <code>ANTHROPIC_API_KEY</code> in <code>apps/web/.env.local</code>; the examples
                above run with no key.
              </footer>
            </>
          )}
        </div>
      </main>
    </div>
  );
}
